/**
 * HelloWorld - Java 入门程序
 * 
 * 这是学习 Java 的第一个程序，演示了最基本的程序结构：
 * 1. 类的定义
 * 2. main 方法（程序入口）
 * 3. 控制台输出
 */
public class HelloWorld {
    /**
     * main 方法是 Java 程序的入口点
     * JVM（Java 虚拟机）从这里开始执行程序
     * 
     * @param args 命令行参数数组，可在运行时传入参数
     */
    public static void main(String[] args) {
        // System.out.println() 用于在控制台输出内容并换行
        // 这是 Java 中最常用的输出语句
        System.out.println("Hello World");
    }
}
