/**
 * Flyable - 飞行接口
 * 
 * 本接口演示：
 * 1. 接口（Interface）的定义
 * 2. 接口中的方法默认是 public abstract 的
 * 
 * 接口是 Java 中实现多态的另一种方式：
 * - 接口只定义方法的签名，不定义实现
 * - 一个类可以实现多个接口（多重继承的替代方案）
 * - 接口表示"能做什么"（能力），抽象类表示"是什么"（类别）
 */
public interface Flyable {
    
    /**
     * fly 方法：飞行的能力
     * 接口中的方法没有方法体，由实现类提供具体实现
     */
    void fly();
}
